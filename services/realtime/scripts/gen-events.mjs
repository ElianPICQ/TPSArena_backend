// Generate src/generated/events.ts from contracts/events.json (JSON Schema exported by tpsarena-common).
// Runs before build and test: a format change in the contract breaks the TypeScript build.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const contract = JSON.parse(readFileSync(join(root, "contracts", "events.json"), "utf8"));
const version = readFileSync(join(root, "contracts", "VERSION"), "utf8").trim();

const parts = [
  `// Generated by scripts/gen-events.mjs from contracts/events.json (tpsarena-common ${version}). Do not edit.`,
  "",
];
// Field titles ("User Id"...) would each become a named type, duplicated across events: inline them.
function stripFieldTitles(node) {
  if (Array.isArray(node)) return node.forEach(stripFieldTitles);
  if (node && typeof node === "object") {
    for (const field of Object.values(node.properties ?? {})) delete field.title;
    Object.values(node).forEach(stripFieldTitles);
  }
}

const names = {};
for (const [type, { schema }] of Object.entries(contract.events)) {
  stripFieldTitles(schema);
  const name = schema.title;
  names[type] = name;
  const ts = await compile(schema, name, { bannerComment: "", additionalProperties: false, declareExternallyReferenced: true });
  parts.push(ts.trim(), "");
}
parts.push("/** The `data` of each event type. */", "export interface EventDataByType {");
for (const [type, name] of Object.entries(names)) parts.push(`  ${JSON.stringify(type)}: ${name};`);
parts.push("}", "", "export type EventType = keyof EventDataByType;", "");
parts.push("/** The stream each event type is published on. */", "export const EVENT_STREAMS = {");
for (const [type, { stream }] of Object.entries(contract.events)) parts.push(`  ${JSON.stringify(type)}: ${JSON.stringify(stream)},`);
parts.push("} as const satisfies Record<EventType, string>;", "");
parts.push(`export const CONTRACT_VERSION = ${JSON.stringify(version)};`, "");

mkdirSync(join(root, "src", "generated"), { recursive: true });
// Duplicate helper types (e.g. MatchPlayerResult) can appear in several schemas: keep the first.
const seen = new Set();
const out = parts.join("\n").replace(/export interface (\w+) \{[\s\S]*?\n\}\n?/g, (block, name) => {
  if (seen.has(name)) return "";
  seen.add(name);
  return block;
});
writeFileSync(join(root, "src", "generated", "events.ts"), out);
console.log(`src/generated/events.ts: ${Object.keys(names).length} event types (contract ${version})`);
